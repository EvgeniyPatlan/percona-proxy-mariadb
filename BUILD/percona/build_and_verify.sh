#!/bin/bash
#
# Builds the packages in a container for each platform and then verifies the packages that came
# out, with no repository in between. This is the whole round trip on one machine: the same
# builder stages Jenkins runs, followed by verify_packages.sh against the files they produce.
#
# It exists because the two halves could otherwise only be joined through repo.percona.com, and
# the repository for this product is not provisioned yet. It is also the quickest way to find
# out whether a change to the packaging still produces an installable package.
#
# Docker is used on the host, so this cannot run inside a container without a Docker socket.
#
# Usage: build_and_verify.sh [OPTIONS]
#     --platforms=LIST    Space separated subset of: el8 el9 el10 amzn2023 jammy noble
#                         bookworm trixie (default: all of them)
#     --repo=PATH|URL     Where to build from (default: the repository holding this script)
#     --branch=NAME       Branch to build (default: the current branch, or main for a URL)
#     --version=X.Y.Z     Version to build (default: 1.0.0)
#     --rpm-release=N     RPM release value (default: 1)
#     --deb-release=N     DEB release value (default: 1)
#     --workdir=DIR       Where to build (default: ./build-and-verify)
#     --port-base=N       First of the five ports used on the host (default: 3000)
#     --build-only        Build the packages and stop
#     --verify-only       Verify packages already in WORKDIR/packages
#     --keep              Keep the build trees, which are several GB per platform
#     --help
#
# The packages of every platform land together in WORKDIR/packages, which is the layout
# verify_packages.sh --packages expects.

set -o pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)

PLATFORMS="el8 el9 el10 amzn2023 jammy noble bookworm trixie"
REPO=
BRANCH=
VERSION=1.0.0
RPM_RELEASE=1
DEB_RELEASE=1
WORKDIR=
PORT_BASE=3000
BUILD_ONLY=0
VERIFY_ONLY=0
KEEP=0

die() {
    echo "ERROR: $*" >&2
    exit 1
}

# The distribution each platform is built in. The builder works out the package naming from the
# container it runs in, so this mapping is what decides the dist tag and the codename.
platform_image() {
    case "$1" in
        el8)      echo "oraclelinux:8" ;;
        el9)      echo "oraclelinux:9" ;;
        el10)     echo "oraclelinux:10" ;;
        amzn2023) echo "amazonlinux:2023" ;;
        jammy)    echo "ubuntu:22.04" ;;
        noble)    echo "ubuntu:24.04" ;;
        bookworm) echo "debian:12" ;;
        trixie)   echo "debian:13" ;;
        *)        return 1 ;;
    esac
}

platform_kind() {
    case "$1" in
        el*|amzn*) echo rpm ;;
        *)         echo deb ;;
    esac
}

parse_options() {
    local arg val
    for arg in "$@"
    do
        val=${arg#*=}
        case "$arg" in
            --platforms=*)   PLATFORMS="$val" ;;
            --repo=*)        REPO="$val" ;;
            --branch=*)      BRANCH="$val" ;;
            --version=*)     VERSION="$val" ;;
            --rpm-release=*) RPM_RELEASE="$val" ;;
            --deb-release=*) DEB_RELEASE="$val" ;;
            --workdir=*)     WORKDIR="$val" ;;
            --port-base=*)   PORT_BASE="$val" ;;
            --build-only)    BUILD_ONLY=1 ;;
            --verify-only)   VERIFY_ONLY=1 ;;
            --keep)          KEEP=1 ;;
            --help)          sed -n '3,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
            *)               die "Unknown option: $arg" ;;
        esac
    done
}

# Writes the script that runs inside the container. Generating it instead of passing a command
# line keeps the quoting readable, and leaves the exact commands on disk after a failure.
write_stage_script() {
    local platform=$1 kind=$2 path=$3 bootstrap
    # A local repository is bind mounted at /src, so that is the path the builder is given;
    # a URL is passed through as it is.
    local container_repo="$REPO"
    [ -d "$REPO" ] && container_repo=/src

    if [ "$kind" = rpm ]
    then
        # Not curl: Amazon Linux 2023 ships curl-minimal, and asking for curl fails the whole
        # transaction, which used to leave git uninstalled and the failure surfacing much later.
        bootstrap='yum -y install git wget tar gzip which findutils > /dev/null 2>&1 \
    || yum -y install --allowerasing git wget tar gzip which findutils'
    else
        bootstrap='export DEBIAN_FRONTEND=noninteractive
apt-get update > /dev/null 2>&1
apt-get install -y -qq git wget curl ca-certificates > /dev/null 2>&1'
    fi

    cat > "$path" <<STAGE
#!/bin/bash
# Generated by build_and_verify.sh for $platform. Runs as root inside $(platform_image "$platform").
set -o errexit
set -o xtrace

$bootstrap

# The source may be a bind mount owned by another user, which git refuses to read otherwise.
git config --global --add safe.directory '*'

cp /src/BUILD/percona/percona_proxy_builder.sh /usr/local/bin/ppb.sh
chmod +x /usr/local/bin/ppb.sh

# The builder requires the directory to exist already.
mkdir -p /work/build

run_stage() {
    local marker=\$1; shift
    if ! ppb.sh --builddir=/work/build --repo='$container_repo' --branch='$BRANCH' \\
        --version='$VERSION' --rpm_release='$RPM_RELEASE' --deb_release='$DEB_RELEASE' \\
        "\$@" > "/work/\$marker.log" 2>&1
    then
        tail -40 "/work/\$marker.log"
        touch "/work/\$marker.FAILED"
        exit 1
    fi
}

run_stage deps    --install_deps=1
run_stage sources --get_sources=1
STAGE

    if [ "$kind" = rpm ]
    then
        cat >> "$path" <<'STAGE'
run_stage srcpkg --build_src_rpm=1
run_stage binpkg --build_rpm=1
STAGE
    else
        cat >> "$path" <<'STAGE'
run_stage srcpkg --build_source_deb=1
run_stage binpkg --build_deb=1
STAGE
    fi

    echo 'touch /work/PKG_OK' >> "$path"
}

build_platform() {
    local platform=$1
    local kind image dir
    kind=$(platform_kind "$platform")
    image=$(platform_image "$platform") || die "Unknown platform: $platform"
    dir="$WORKDIR/$platform"

    echo "== $platform: building in $image"
    rm -rf "$dir"
    mkdir -p "$dir"
    write_stage_script "$platform" "$kind" "$dir/stage.sh"

    local mounts=(-v "$dir:/work")
    # A local repository has to be visible inside the container as well.
    if [ -d "$REPO" ]
    then
        mounts+=(-v "$(cd "$REPO" && pwd):/src:ro")
    else
        mounts+=(-v "$SOURCE_TREE:/src:ro")
    fi

    if ! docker run --rm -u root "${mounts[@]}" "$image" bash /work/stage.sh \
        > "$dir/docker.log" 2>&1
    then
        echo "   $platform BUILD FAILED, see $dir"
        tail -20 "$dir/docker.log" | sed 's/^/     /'
        return 1
    fi

    local found=0
    if [ "$kind" = rpm ]
    then
        while IFS= read -r pkg
        do
            cp "$pkg" "$WORKDIR/packages/"
            found=$((found + 1))
        done < <(find "$dir/build" -name "*.rpm" ! -name "*.src.rpm")
    else
        while IFS= read -r pkg
        do
            cp "$pkg" "$WORKDIR/packages/"
            found=$((found + 1))
        done < <(find "$dir/build" -name "*.deb")
    fi

    [ "$found" -gt 0 ] || { echo "   $platform produced no packages"; return 1; }
    echo "   $platform built $found package(s)"

    if [ "$KEEP" -eq 0 ]
    then
        # The build tree is several GB and nothing after this reads it.
        docker run --rm -v "$dir:/work" "$image" rm -rf /work/build 2>/dev/null \
            || rm -rf "$dir/build" 2>/dev/null
    fi
}

main() {
    parse_options "$@"

    command -v docker > /dev/null || die "docker is required"
    docker info > /dev/null 2>&1 || die "cannot talk to the Docker daemon"

    # Default to the repository this script lives in.
    SOURCE_TREE=$(cd "$SCRIPT_DIR/../.." && pwd)
    [ -n "$REPO" ] || REPO="$SOURCE_TREE"
    if [ -z "$BRANCH" ]
    then
        if [ -d "$REPO/.git" ]
        then
            BRANCH=$(git -C "$REPO" rev-parse --abbrev-ref HEAD)
        else
            BRANCH=main
        fi
    fi
    [ -n "$WORKDIR" ] || WORKDIR="$PWD/build-and-verify"
    mkdir -p "$WORKDIR/packages" || die "Cannot create $WORKDIR"
    WORKDIR=$(cd "$WORKDIR" && pwd)

    local platform failed=
    if [ "$VERIFY_ONLY" -eq 0 ]
    then
        echo "Building $VERSION from $REPO ($BRANCH)"
        for platform in $PLATFORMS
        do
            build_platform "$platform" || failed="$failed $platform"
        done

        if [ -n "$failed" ]
        then
            echo
            echo "Build failed for:$failed"
            return 1
        fi
    fi

    if [ "$BUILD_ONLY" -eq 1 ]
    then
        echo
        echo "Packages are in $WORKDIR/packages"
        return 0
    fi

    echo
    echo "Verifying the packages that were just built"
    "$SCRIPT_DIR/verify_packages.sh" --packages="$WORKDIR/packages" --version="$VERSION" \
        --platforms="$PLATFORMS" --port-base="$PORT_BASE"
}

main "$@"
